import assert from "node:assert/strict";
import { Window } from "happy-dom";
const dom = new Window({ url: "https://chvostikovo.sk/" });
globalThis.window = dom;
globalThis.document = dom.document;
globalThis.CustomEvent = dom.CustomEvent;
const consent = await import("../src/lib/consent.ts");
assert.equal(consent.readStoredConsent(), null);
let changes = 0;
dom.addEventListener("chvostikovo-consent-changed", () => changes++);
Object.defineProperty(dom, "localStorage", { configurable: true, get() { throw new DOMException("Blocked storage", "SecurityError"); } });
assert.doesNotThrow(() => consent.readStoredConsent());
assert.equal(consent.hasAnalyticsConsent(), false);
assert.equal(consent.hasMarketingConsent(), false);
assert.doesNotThrow(() => consent.writeStoredConsent({ functional: false, analytics: false, marketing: false }));
assert.equal(changes, 1);
assert.equal(consent.hasAnalyticsConsent(), false);
consent.writeStoredConsent({ functional: true, analytics: true, marketing: false });
assert.equal(consent.hasAnalyticsConsent(), true);
assert.equal(consent.hasMarketingConsent(), false);
Object.defineProperty(dom, "localStorage", { configurable: true, value: { getItem: () => null, setItem() { throw new DOMException("Full", "QuotaExceededError"); } } });
consent.writeStoredConsent({ functional: false, analytics: false, marketing: false });
assert.equal(consent.hasAnalyticsConsent(), false);
assert.equal(consent.hasMarketingConsent(), false);
let stored = null;
Object.defineProperty(dom, "localStorage", { configurable: true, value: { getItem: () => stored, setItem(key, value) { stored = value; } } });
consent.writeStoredConsent({ functional: true, analytics: true, marketing: true });
assert.equal(consent.readStoredConsent().marketing, true);
stored = JSON.stringify({ ...consent.readStoredConsent(), version: "old" });
assert.equal(consent.readStoredConsent(), null);
console.log("PASS: consent survives blocked getter/read/write, quota failure; denied by default; explicit choices and stored consent preserved");
await dom.happyDOM.close();
