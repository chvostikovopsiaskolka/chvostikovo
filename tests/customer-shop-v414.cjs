const fs=require('node:fs'),assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const app=fs.readFileSync('app.js','utf8');
const css=fs.readFileSync('customer-design.css','utf8');
const locale=fs.readFileSync('customer-locale-v409.js','utf8');
const ver=JSON.parse(fs.readFileSync('version.json','utf8'));
assert(Number(ver.build.slice(1))>=414,'shop feature must remain in current or newer builds');
assert(app.includes(`const APP_BUILD='${ver.build}';`),'app and manifest build versions stay synchronized');
const shop=html.match(/<a id="customerShopV414"[^>]*>[\s\S]*?<\/a>/);
assert(shop,'customer e-shop dock link exists');
assert(shop[0].includes('href="https://chvostikovo.sk/produkty/"'));
assert(shop[0].includes('target="_blank"'));
assert(shop[0].includes('rel="noopener noreferrer"'));
assert(shop[0].includes('E-shop'));
assert(shop[0].includes('#ci-shop-v414'));
assert(!html.includes('id="customerAnnouncementsV363"'),'notices shortcut removed from bottom dock');
assert((html.match(/id="customerAnnouncementsCountV363"/g)||[]).length===1,'unread notices badge has one owner');
const menu=html.match(/<button id="menuBulletinV229"[\s\S]*?<\/button>/);
assert(menu?.[0].includes('customerAnnouncementsCountV363'),'notices and count retained in menu');
assert(html.indexOf('<nav class="bottom-nav"')<html.indexOf('id="customerShopV414"'),'shop sits inside bottom nav');
assert(html.indexOf('id="customerShopV414"')<html.indexOf('id="navDog"'),'shop replaces the fourth nav slot');
assert(app.includes("$('menuBulletinV229')?.addEventListener('click',()=>openHistory(true))"),'notice menu button remains wired');
assert(app.includes("$('menuBulletinV229')?.setAttribute('aria-label',count?"),'menu has unread accessible label');
assert(css.includes('.customer-design .bottom-nav #customerShopV414:focus-visible'),'shop anchor retains keyboard focus');
assert(css.includes('#menuBulletinV229 .customer-menu-notice-count-v414:not(.hidden)'),'unread badge moves out of dock');
assert(locale.includes("DICTIONARY.set('E-shop','Shop')"),'SK/EN shop label');
assert(html.includes('id="dogVaccinationsLaterV413"'),'preceding v413 vaccination defer behavior preserved');
assert(html.includes('class="dog-required-marker-v413"'),'preceding v413 required labels preserved');
assert(!html.includes('id="customerShopV414" href="/kosik"'),'no abandoned checkout');
console.log('PASS v414: product catalog is external, notice menu and unread remain, dock geometry/locale/onboarding preserved');
