const fs=require('node:fs');const assert=require('node:assert/strict');const {JSDOM}=require('jsdom');
const script=fs.readFileSync('customer-locale-v408.js','utf8');
const markup='<main id="authView"><section><h1 id="authFormTitleV403">Prihlásenie</h1><label for="email">E-mail</label><input id="email" value="synthetic@example.invalid"><p>Podľa mena ho priradíme k vášmu účtu.</p><div id="authMessage"></div><div id="customerLocaleSwitchV408"><button type="button" data-customer-locale="sk">SK</button><button type="button" data-customer-locale="en">EN</button></div><p id="customerLocaleNoteV408"></p></section></main>';
const flush=()=>new Promise(resolve=>setImmediate(resolve));
(async()=>{
 const dom=new JSDOM(markup,{url:'https://app.chvostikovo.sk/?lang=en',runScripts:'outside-only',pretendToBeVisual:true});
 const {window:w}=dom;
 w.eval(script);
 await flush();
 assert.equal(w.document.documentElement.lang,'en');
 assert.equal(w.document.querySelector('h1').textContent,'Sign in');
 assert.equal(w.document.querySelector('label').textContent,'Email');
 assert.equal(w.document.querySelector('input').value,'synthetic@example.invalid');
 assert.equal(w.localStorage.getItem('chvostikovo-customer-locale-v408'),'en');
 assert.equal(w.document.querySelector('[data-customer-locale=en]').getAttribute('aria-pressed'),'true');
 assert.match(w.document.getElementById('customerLocaleNoteV408').textContent,/legal documents/);
 w.document.getElementById('authFormTitleV403').textContent='Obnova hesla';
 await flush();
 assert.equal(w.document.querySelector('h1').textContent,'Reset password');
 w.document.querySelector('[data-customer-locale=sk]').click();
 await flush();
 assert.equal(w.document.querySelector('h1').textContent,'Obnova hesla');
 assert.equal(w.document.querySelector('label').textContent,'E-mail');
 assert.equal(w.localStorage.getItem('chvostikovo-customer-locale-v408'),'sk');
 w.document.querySelector('[data-customer-locale=en]').click();
 await flush();
 assert.equal(w.document.querySelector('h1').textContent,'Reset password');
 assert.equal(w.document.querySelector('input').value,'synthetic@example.invalid');
 assert.equal(w.document.querySelectorAll('input').length,1);
 assert.equal(w.document.getElementById('authMessage').textContent,'');
 w.close();
 console.log('PASS: EN link persistence, SK/EN toggle, dynamic auth title, original form unchanged');
})().catch(e=>{console.error(e);process.exitCode=1});