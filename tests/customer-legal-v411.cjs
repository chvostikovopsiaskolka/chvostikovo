const fs=require('node:fs'),assert=require('node:assert/strict'),{JSDOM}=require('jsdom');
const dom=new JSDOM('<main id="authView"><div id="customerLocaleSwitchV408"><button data-customer-locale="sk">SK</button><button data-customer-locale="en">EN</button></div></main>',{url:'https://app.chvostikovo.sk/?lang=en',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window;
w.eval(fs.readFileSync('customer-locale-v409.js','utf8'));
w.eval(fs.readFileSync('customer-legal-en-v411.js','utf8'));
const module=w.ChvostikovoLegalENV411;
assert(module,'Terms must load into page before app initialization');
const doc={version:'2026-10-03',document_hash:module.HASH,title:'Podmienky psej škôlky Chvostíkovo',body:'Source document stays authoritative'};
const english=module.view(doc);
assert.notEqual(english,doc,'Display view is a copy, not the accepted canonical source');
assert.equal(english.__englishReadingTranslation,true);
assert.equal(english.title,'Chvostíkovo Dog Daycare Terms');
assert.equal(english.document_hash,doc.document_hash);
assert.equal(english.version,doc.version);
assert.equal(doc.body,'Source document stays authoritative');
assert.equal((english.body.match(/^\d+\. /gm)||[]).length,10,'Every one of the ten sections must have EN content');
assert.match(english.body,/7:00 PM/,'Keep original previous-day cancellation deadline');
assert.match(english.body,/two months from the first visit/,'Keep pass expiry rule');
assert.match(english.body,/owner bears the costs of veterinary treatment/,'Keep allocation of vet costs');
assert.match(english.body,/failure to provide appropriate supervision/,'Keep liability exceptions');
assert.match(module.notice,/Slovak.*authoritative/,'Do not present non-vetted translation as the source');
assert.equal(module.view({...doc,document_hash:'different'}).body,doc.body,'Unknown checksum never receives outdated EN terms');
assert.equal(module.view({...doc,version:'future-version'}).body,doc.body,'Unknown version never receives outdated EN terms');
w.ChvostikovoLocale.setLanguage('sk');
assert.equal(module.view(doc),doc,'SK always displays the original source');
w.ChvostikovoLocale.setLanguage('en');
assert.equal(module.view(doc).body,english.body,'Switching languages preserves the exact EN reading content');
const app=fs.readFileSync('app.js','utf8');
assert(app.includes("p_document_hash:modal.dataset.documentHash"),'Server receives source hash, never display translation hash');
assert(app.includes("p_acceptance_text:TERMS_ACCEPTANCE_TEXT"),'Original legal acceptance payload stays unchanged');
assert(app.includes('window.ChvostikovoLegalENV411?.view(doc)'));
assert(!app.includes('p_acceptance_text:english'),'Do not upload translated acceptance text');
w.close();
console.log('PASS: hash/version-pinned full ten-section EN reading text; immutable source, consent and PDF');
